import { REGISTRY } from "./settings/registry.ts";
import { SEED_CATEGORIES, SEED_THEMES, TEST_LIVE_VERSIONS, TEST_SUPER_USER, builtinBackground, builtinThumbnail, defaultLayout } from "./seed-data.ts";

const q = (s: string | null | undefined) => (s === null || s === undefined ? "null" : `'${s.replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (xs: string[]) => `array[${xs.map(q).join(", ")}]::text[]`;
const mmdd = (s: string | null) => (s ? q(`2026-${s}`) : "null");

export function buildSeedSql(): string {
  const out: string[] = [];
  out.push("-- GENERATED by scripts/gen-seed.ts from lib/settings/registry.ts and lib/seed-data.ts. Do not edit by hand.");
  out.push("-- The live project's seed: every version is draft and every switch is off.");
  out.push("-- Idempotent: on conflict do nothing, so re-running never overwrites what a super user changed.");
  out.push("");
  out.push("insert into public.settings (key, value, type, section, label, description, options, updated_by, updated_at) values");
  const rows = Object.entries(REGISTRY).map(([key, d]) => {
    const def = d as { type: string; section: string; label: string; description?: string; default: unknown; options?: readonly string[] };
    return `  (${q(key)}, ${j(def.default)}, ${q(def.type)}, ${q(def.section)}, ${q(def.label)}, ${q(def.description ?? null)}, ${def.options ? j(def.options) : "null"}, 'seed', now())`;
  });
  out.push(rows.join(",\n") + "\non conflict (key) do nothing;");
  out.push("");
  out.push("insert into public.super_users (email, added_by) values ('gavin@storyboards.io', 'seed'), ('gideon@storyboards.io', 'seed') on conflict (email) do nothing;");
  out.push("");
  out.push("insert into public.theme_categories (slug, name, sort_order) values");
  out.push(SEED_CATEGORIES.map((c) => `  (${q(c.slug)}, ${q(c.name)}, ${c.sort})`).join(",\n") + "\non conflict (slug) do nothing;");
  out.push("");
  for (const t of SEED_THEMES) {
    out.push(
      `insert into public.themes (slug, name, category_id, available_from, available_to, repeats_yearly, sort_order, status)\n` +
        `select ${q(t.slug)}, ${q(t.name)}, c.id, ${mmdd(t.from)}, ${mmdd(t.to)}, true, ${t.sort}, 'live' from public.theme_categories c where c.slug = ${q(t.category)}\n` +
        `on conflict (slug) do nothing;`,
    );
    t.versions.forEach((v, i) => {
      out.push(
        `insert into public.theme_versions (theme_id, slug, name, status, is_new, sort_order, background_path, thumbnail_path, layout, message_ideas)\n` +
          `select t.id, ${q(v.slug)}, ${q(v.name)}, 'draft', ${v.isNew ? "true" : "false"}, ${i + 1}, ${q(builtinBackground(t.slug, v.slug))}, ${q(builtinThumbnail(t.slug, v.slug))}, ${j(defaultLayout(v.look))}, ${arr(v.ideas)} from public.themes t where t.slug = ${q(t.slug)}\n` +
          `on conflict (theme_id, slug) do nothing;`,
      );
    });
  }
  return out.join("\n") + "\n";
}

export function buildTestSeedSql(): string {
  const out: string[] = [];
  out.push("-- GENERATED by scripts/gen-seed.ts. LOCAL TEST STACK ONLY: never apply to magic-vault.");
  out.push("-- Runs after seed.sql on `supabase db reset`: live versions, cards on, fixture super user.");
  out.push("");
  out.push(`update public.settings set value = 'true'::jsonb, updated_by = 'seed-test', updated_at = now() where key = 'cards.enabled';`);
  out.push(`insert into public.super_users (email, added_by) values (${q(TEST_SUPER_USER)}, 'seed-test') on conflict (email) do nothing;`);
  // Every e2e request comes from one IP: lift the per-IP limits locally.
  for (const k of ["auth.link_ip_rate_limit_per_hour", "auth.code_ip_rate_limit_per_hour", "auth.code_rate_limit_per_hour", "auth.verify_rate_limit_per_hour", "redeem.download_rate_limit_per_hour", "vault.lookup_rate_limit_per_hour", "gift.offer_link_rate_limit_per_hour"]) {
    out.push(`update public.settings set value = '100000'::jsonb, updated_by = 'seed-test' where key = ${q(k)};`);
  }
  for (const tv of TEST_LIVE_VERSIONS) {
    const [theme, version] = tv.split("/");
    out.push(
      `update public.theme_versions v set status = 'live', published_at = now() from public.themes t where v.theme_id = t.id and t.slug = ${q(theme)} and v.slug = ${q(version)};`,
    );
  }
  return out.join("\n") + "\n";
}
